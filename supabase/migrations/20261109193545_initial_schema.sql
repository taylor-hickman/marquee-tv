-- Every table in architecture 5.1, 5.2 and 5.4.
-- Catalog ids are bigint so a candidate row sent to the model stays short (architecture 6.2).
-- Ids that appear in URLs or bearer contexts (drafts, guests, runs) are uuid.

create extension if not exists pg_trgm with schema extensions;

-- 5.1 Catalog

create table publisher (
  id bigint generated by default as identity primary key,
  name text not null unique,
  channel_id text not null unique,
  channel_url text not null
);

create table series (
  id bigint generated by default as identity primary key,
  publisher_id bigint not null references publisher (id),
  name text not null,
  uploads_playlist_id text not null,
  title_rule text not null,
  launch_depth text not null check (launch_depth in ('full', 'thin')),
  convention text not null,
  unique (publisher_id, name)
);

create table artist (
  id bigint generated by default as identity primary key,
  name text not null,
  review_status text not null default 'pending'
    check (review_status in ('pending', 'accepted', 'flagged', 'rejected'))
);

create table artist_alias (
  artist_id bigint not null references artist (id) on delete cascade,
  alias text not null,
  primary key (artist_id, alias)
);

-- One row per artist: an editor row replaces the model row and ingestion must not overwrite it.
create table artist_profile (
  artist_id bigint primary key references artist (id) on delete cascade,
  genres text[] not null default '{}',
  scenes text[] not null default '{}',
  era text,
  energy smallint not null check (energy between 1 and 5),
  similar_artist_ids bigint[] not null default '{}',
  source text not null check (source in ('model', 'editor')),
  updated_at timestamptz not null default now()
);

create table performance (
  id bigint generated by default as identity primary key,
  video_id text not null unique check (video_id ~ '^[A-Za-z0-9_-]{11}$'),
  series_id bigint not null references series (id),
  eligible boolean not null default false,
  -- null until classified
  kind text check (kind in ('performance', 'interview', 'trailer', 'clip')),
  review_status text not null default 'pending'
    check (review_status in ('pending', 'accepted', 'flagged', 'rejected')),
  last_verified_at timestamptz,
  created_at timestamptz not null default now()
);

create index performance_series_id_idx on performance (series_id);

create table performance_artist (
  performance_id bigint not null references performance (id) on delete cascade,
  artist_id bigint not null references artist (id),
  billing_order smallint not null check (billing_order >= 1),
  primary key (performance_id, artist_id),
  unique (performance_id, billing_order)
);

create index performance_artist_artist_id_idx on performance_artist (artist_id);

-- Everything that came from the YouTube API (architecture 5.3). TRUNCATE this table to drop it all.
create table performance_yt_cache (
  performance_id bigint primary key references performance (id) on delete cascade,
  title text not null,
  duration_s integer not null check (duration_s > 0),
  published_at timestamptz not null,
  available boolean not null,
  fetched_at timestamptz not null default now()
);

-- P1: created empty (architecture 11).
create table performance_tag (
  id bigint generated by default as identity primary key,
  performance_id bigint not null references performance (id) on delete cascade,
  kind text not null check (kind in ('energy', 'mood', 'instrumentation')),
  value text not null,
  source text not null check (source in ('feedback', 'editor')),
  created_at timestamptz not null default now()
);

-- Search: full-text over titles and artist names, trigram typeahead on names and aliases.
-- Queries must use the same expressions to hit these indexes.
create index performance_yt_cache_title_fts_idx
  on performance_yt_cache using gin (to_tsvector('simple', title));
create index artist_name_fts_idx
  on artist using gin (to_tsvector('simple', name));
create index artist_name_trgm_idx
  on artist using gin (name extensions.gin_trgm_ops);
create index artist_alias_alias_trgm_idx
  on artist_alias using gin (alias extensions.gin_trgm_ops);

-- 5.4 Accounts, billing and events (before 5.2, which references them)

create table app_user (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null unique,
  created_at timestamptz not null default now()
);

create table guest (
  id uuid primary key default gen_random_uuid(),
  -- SHA-256 of the bearer token; the token itself is never stored
  token_hash bytea not null unique check (octet_length(token_hash) = 32),
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  ip_hash bytea,
  cohort text not null check (cohort in ('pass_first', 'sub_first'))
);

create table entitlement (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references app_user (id) on delete cascade,
  kind text not null check (kind in ('session_pass', 'subscription')),
  status text not null,
  period_end timestamptz,
  draft_id uuid,
  stripe_customer_id text,
  stripe_subscription_id text unique,
  stripe_payment_intent_id text unique,
  created_at timestamptz not null default now()
);

create index entitlement_user_id_idx on entitlement (user_id);

create table app_flag (
  key text primary key,
  value text not null
);

-- 5.2 Playlists

create table playlist_draft (
  id uuid primary key default gen_random_uuid(),
  owner_user_id uuid references app_user (id) on delete cascade,
  owner_guest_id uuid references guest (id) on delete cascade,
  creation_method text not null,
  free boolean not null default false,
  status text not null default 'active'
    check (status in ('active', 'awaiting_payment', 'read_only')),
  -- null until the first revision is written
  current_revision integer,
  entitlement_id uuid references entitlement (id) on delete set null,
  title text,
  description text,
  duration_target_s integer check (duration_target_s > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint playlist_draft_one_owner check (num_nonnulls(owner_user_id, owner_guest_id) = 1)
);

create index playlist_draft_owner_user_id_idx on playlist_draft (owner_user_id);
create index playlist_draft_owner_guest_id_idx on playlist_draft (owner_guest_id);

-- At most one free draft per guest and per user.
create unique index playlist_draft_one_free_per_user
  on playlist_draft (owner_user_id) where free and owner_user_id is not null;
create unique index playlist_draft_one_free_per_guest
  on playlist_draft (owner_guest_id) where free and owner_guest_id is not null;

alter table entitlement
  add constraint entitlement_draft_id_fkey
  foreign key (draft_id) references playlist_draft (id) on delete set null;

-- Outlives its draft: retention removes the draft link and keeps brief and output ids for evals.
create table curator_run (
  id uuid primary key default gen_random_uuid(),
  draft_id uuid references playlist_draft (id) on delete set null,
  kind text not null,
  brief jsonb,
  candidate_ids bigint[] not null default '{}',
  output_ids bigint[] not null default '{}',
  warnings jsonb not null default '[]',
  model text,
  tokens_in integer,
  tokens_out integer,
  latency_ms integer,
  error text,
  created_at timestamptz not null default now()
);

create index curator_run_draft_id_idx on curator_run (draft_id);
create index curator_run_created_at_idx on curator_run (created_at);

-- Immutable snapshots: the only store of playlist items.
create table playlist_revision (
  draft_id uuid not null references playlist_draft (id) on delete cascade,
  number integer not null check (number >= 1),
  items jsonb not null default '[]' check (jsonb_typeof(items) = 'array'),
  removed_ids jsonb not null default '[]' check (jsonb_typeof(removed_ids) = 'array'),
  brief jsonb,
  trigger text not null check (trigger in ('generate', 'refine', 'edit', 'undo', 'regenerate')),
  instruction text,
  curator_run_id uuid references curator_run (id) on delete set null,
  created_at timestamptz not null default now(),
  primary key (draft_id, number)
);

create table share_link (
  code text primary key,
  draft_id uuid not null,
  revision integer not null,
  start_index integer not null default 0 check (start_index >= 0),
  created_at timestamptz not null default now(),
  unique (draft_id, revision, start_index),
  foreign key (draft_id, revision) references playlist_revision (draft_id, number) on delete cascade
);

create table handoff_event (
  id bigint generated by default as identity primary key,
  draft_id uuid references playlist_draft (id) on delete set null,
  revision integer,
  type text not null check (type in ('open', 'copy', 'share')),
  part integer check (part >= 1),
  start_index integer not null default 0 check (start_index >= 0),
  surface text,
  created_at timestamptz not null default now()
);

create table event (
  id bigint generated by default as identity primary key,
  name text not null,
  guest_id uuid references guest (id) on delete set null,
  user_id uuid references app_user (id) on delete set null,
  draft_id uuid references playlist_draft (id) on delete set null,
  props jsonb not null default '{}',
  created_at timestamptz not null default now()
);

create index event_name_created_at_idx on event (name, created_at);

